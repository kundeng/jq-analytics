"""skill_build: build and check the agent skill in skills/jq-analytics/.

Usage (from the repository root):
    python tools/skill_build.py <jq binary> [<jq binary> ...]

Writes skills/jq-analytics/references/functions.md: every public function of analytics.jq, by
family, with how it is called and the first sentence of its read-out note. Then checks SKILL.md:
  - every name in backticks that looks like a call of this library (`name` or `name(...)`) and is
    not a jq built-in must be a public function, so a rename cannot leave the skill stale;
  - every ```jq block that is followed by a ```json block is run on each engine named, with
    'include "analytics";' in front, and must print that json (key order and 2 against 2.0 aside).
Stops with a list of what is wrong; prints {"functions": n, "runs": n, "names": n} when all is well.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import readout  # noqa: E402  the same parser and runner the read-out uses

SKILL = readout.ROOT / "skills" / "jq-analytics"
WORDS = {"_", "jq_analytics", "true", "false", "null", "jq", "include", "import", "def", "as", "if", "then", "else", "end", "reduce", "foreach"}


def functions_page(families: list[dict]) -> str:
    lines = ["# Functions of jq-analytics", "",
             "Generated by `tools/skill_build.py` from `analytics.jq` and the read-out notes. One line per public function: how it is called, and what it is for. An argument with `$` is a value; one without is a filter, run on each row (write `.site`, not `site` or `\"site\"`). Exact rules for nulls, ties and errors are in the README's Reference.", ""]
    count = 0
    for family in families:
        path = readout.NOTES / f"{family['slug']}.md"
        notes = readout.read_notes(path)[1:] if path.exists() else []
        if not notes:
            continue
        rows = []
        for note in notes:
            calls = [readout.DEF.match(d["code"][0]).group(0)[4:-1] for d in family["defs"] if d["key"] in note["keys"] and not d["key"].startswith("_")]
            if calls:
                rows.append("| " + ", ".join(f"`{c}`" for c in calls) + f" | {readout.purpose(note)} |")
                count += len(calls)
        if rows:
            lines += [f"## {family['name'][0].upper() + family['name'][1:]}", "", "| Call | What it is for |", "|---|---|"] + rows
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n", count


def main() -> None:
    engines = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not engines:
        raise SystemExit(__doc__)
    families = readout.parse(readout.SOURCE.read_text())
    page, count = functions_page(families)
    (SKILL / "references").mkdir(parents=True, exist_ok=True)
    (SKILL / "references" / "functions.md").write_text(page)
    library = {d["key"].split("/")[0] for family in families for d in family["defs"]}
    public = {n for n in library if not n.startswith("_")}
    builtins = readout.engine_builtins(engines)
    problems: list[str] = []
    text = (SKILL / "SKILL.md").read_text() if (SKILL / "SKILL.md").exists() else ""
    prose = re.sub(r"```.*?```", "", text, flags=re.S)
    names = set()
    for span in re.findall(r"`([^`\n]+)`", prose):
        m = re.fullmatch(r"(?:a::)?([a-z_][a-z0-9_]*)(\(.*\))?", span.strip())
        if m and "_" in m.group(1) or (m and m.group(2)):
            names.add(m.group(1))
    for name in sorted(names - public - builtins - WORDS):
        problems.append(f"SKILL.md names `{name}`, which is neither a public function of the library nor a jq built-in")
    runs = 0
    for program, expected in re.findall(r"```jq\n(.*?)\n```\n+```json\n(.*?)\n```", text, flags=re.S):
        got = readout.run(program, engines)
        runs += 1
        if readout.canonical(got) != readout.canonical("\n".join(json.dumps(json.loads(line)) for line in expected.split("\n") if line.strip())):
            problems.append("SKILL.md shows an output the engines do not give:\n" + program + "\nengines: " + got)
    if problems:
        raise SystemExit("skill not in step with the library:\n" + "\n".join(problems))
    print(json.dumps({"functions": count, "runs": runs, "names": len(names)}))


if __name__ == "__main__":
    main()
